// Package postgres adapts internal/ports to PostgreSQL via pgx and
// sqlc-generated queries (internal/adapters/postgres/gen), enforcing
// workspace isolation via Postgres row-level security
// (docs/MASTER_PLAN.md §5.4, §6.2).
package postgres

import (
	"context"
	"fmt"

	"github.com/jackc/pgx/v5/pgxpool"
)

func NewPool(ctx context.Context, databaseURL string) (*pgxpool.Pool, error) {
	pool, err := pgxpool.New(ctx, databaseURL)
	if err != nil {
		return nil, fmt.Errorf("postgres: create pool: %w", err)
	}
	if err := pool.Ping(ctx); err != nil {
		pool.Close()
		return nil, fmt.Errorf("postgres: ping: %w", err)
	}
	return pool, nil
}
